// s_font_header offsets.
static const DWORD HEADER_VERSION = 0x00;
static const DWORD HEADER_ASCENDING = 0x24;
static const DWORD HEADER_DESCENDING = 0x26;
static const DWORD HEADER_LEADING = 0x28;
static const DWORD HEADER_LOCATION_OFFSET = 0x134;
static const DWORD HEADER_LOCATION_COUNT = 0x138;
static const DWORD HEADER_CHARACTER_OFFSET = 0x140;
static const DWORD HEADER_CHARACTER_SIZE = 0x144;
static const DWORD HEADER_SIZE = 348;

static const DWORD FONT_VERSION = 0xF0000005;
static const DWORD CHARACTER_PAGE_SIZE = 8;
static const DWORD LOCATION_PAGE_INDEX_BITS = 21;
static const DWORD LOCATION_INVALID = 0xFFFFFFFF;
static const DWORD CHARACTER_HEADER_SIZE = 12; // s_font_character

// font_unpack_character_pixels pack modes (top two bits of each byte).
static const BYTE PACK_RLE_0 = 0;
static const BYTE PACK_RLE_1 = 1;
static const BYTE PACK_SINGLE = 2;

static CaptureGlyph g_glyphs[CAPTURE_FONT_CHARACTERS];
static BYTE g_alpha[CAPTURE_FONT_CHARACTERS][CAPTURE_GLYPH_MAX_PIXELS];
static int g_ascent = 0;
static int g_lineHeight = 0;
static BOOL g_initialized = FALSE;
static BOOL g_valid = FALSE;

static DWORD Read32(DWORD offset)
{
	const BYTE* p = g_fontData + offset;
	return p[0] | (p[1] << 8) | (p[2] << 16) | ((DWORD)p[3] << 24);
}

static int Read16(DWORD offset)
{
	const BYTE* p = g_fontData + offset;
	return (short)(p[0] | (p[1] << 8));
}

// Pixels are 16 bit: 4 bit alpha over a 12 bit colour. Only the alpha is
// kept; the font is drawn in one colour.
static BYTE DecodeAlpha(BYTE quantized)
{
	return (BYTE)((quantized << 1) | (quantized & 1));
}

// Port of font_unpack_character_pixels: run-length packed alpha. Returns the
// pixel count, or -1 if the data runs past `max` or the packed size.
static int Unpack(const BYTE* src, int size, BYTE* out, int max)
{
	int n = 0;
	int i = 0;
	while (i < size) {
		BYTE b = src[i];
		BYTE mode = b >> 6;
		if (mode == PACK_RLE_0 || mode == PACK_RLE_1) {
			int run = b & 0x3F;
			if (run != 0 || mode != PACK_RLE_0) {
				if (n + run > max)
					return -1;
				memset(out + n, mode == PACK_RLE_0 ? 0 : DecodeAlpha(7), run);
				n += run;
				i += 1;
			}
			else {
				// New pen colour, the pixel itself follows in two bytes.
				if (i + 2 >= size || n + 1 > max)
					return -1;
				out[n++] = src[i + 1] >> 4;
				i += 3;
			}
		}
		else if (mode == PACK_SINGLE) {
			// One pixel, then an optional short run: 1-3 of 7s, 4-7 of 0s.
			static const int runs[8] = { 0, 4, 3, 2, 5, 4, 3, 2 };
			int extra = b & 7;
			int run = runs[extra];
			if (n + 1 + run > max)
				return -1;
			out[n++] = DecodeAlpha((b >> 3) & 7);
			memset(out + n, extra >= 1 && extra <= 3 ? DecodeAlpha(7) : 0, run);
			n += run;
			i += 1;
		}
		else {
			// Two pixels.
			if (n + 2 > max)
				return -1;
			out[n++] = DecodeAlpha((b >> 3) & 7);
			out[n++] = DecodeAlpha(b & 7);
			i += 1;
		}
	}
	return n;
}

BOOL CaptureFontInitialize()
{
	if (g_initialized)
		return g_valid;
	g_initialized = TRUE;

	int ascending = Read16(HEADER_ASCENDING);
	int descending = Read16(HEADER_DESCENDING);
	int leading = Read16(HEADER_LEADING);
	DWORD locationOffset = Read32(HEADER_LOCATION_OFFSET);
	DWORD locationCount = Read32(HEADER_LOCATION_COUNT);
	DWORD characterOffset = Read32(HEADER_CHARACTER_OFFSET);
	DWORD characterSize = Read32(HEADER_CHARACTER_SIZE);
	if (Read32(HEADER_VERSION) != FONT_VERSION || ascending <= 0 || ascending > 64 || descending < 0 || descending > 64 ||
		leading < 0 || leading > 64 || locationOffset < HEADER_SIZE || locationCount > 0x10000 ||
		locationOffset + locationCount * 4 > sizeof(g_fontData) || characterOffset < HEADER_SIZE ||
		characterOffset + characterSize > sizeof(g_fontData)) {
		return FALSE;
	}
	g_ascent = ascending;
	g_lineHeight = ascending + descending + leading;

	DWORD count = 0;
	for (DWORD c = 0; c < CAPTURE_FONT_CHARACTERS && c < locationCount; c++) {
		DWORD location = Read32(locationOffset + c * 4);
		if (location == LOCATION_INVALID)
			continue;
		DWORD page = location & ((1 << LOCATION_PAGE_INDEX_BITS) - 1);
		DWORD offset = characterOffset + page * CHARACTER_PAGE_SIZE;
		if (offset + CHARACTER_HEADER_SIZE > characterOffset + characterSize)
			continue;

		int advance = Read16(offset + 0x0);
		int packedSize = (WORD)Read16(offset + 0x2);
		int width = Read16(offset + 0x4);
		int height = Read16(offset + 0x6);
		int left = Read16(offset + 0x8);
		int originY = Read16(offset + 0xA);
		if (advance < -256 || advance > 256 || packedSize < 1 || width < 1 || height < 1 ||
			width * height > CAPTURE_GLYPH_MAX_PIXELS || left <= -256 || left >= 256 || originY <= -64 || originY >= 64 ||
			offset + CHARACTER_HEADER_SIZE + packedSize > sizeof(g_fontData))
			continue;
		if (Unpack(g_fontData + offset + CHARACTER_HEADER_SIZE, packedSize, g_alpha[c], width * height) != width * height)
			continue;

		CaptureGlyph* g = &g_glyphs[c];
		g->advance = advance;
		g->left = left;
		g->originY = originY;
		g->width = width;
		g->height = height;
		g->alpha = g_alpha[c];
		count++;
	}
	g_valid = count > 0;
	return g_valid;
}

const CaptureGlyph* CaptureFontGlyph(DWORD character)
{
	if (!g_valid || character >= CAPTURE_FONT_CHARACTERS || !g_glyphs[character].alpha)
		return NULL;
	return &g_glyphs[character];
}

int CaptureFontAscent()
{
	return g_ascent;
}

int CaptureFontLineHeight()
{
	return g_lineHeight;
}
